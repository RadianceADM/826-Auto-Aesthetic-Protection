/** A name inside a sentence: lower case, but "PPF" and "SUV" stay as they are */
const lower = (name: string) =>
    name
        .split(' ')
        .map((word) => (word.length > 1 && word === word.toUpperCase() ? word : word.toLowerCase()))
        .join(' ');

